-- ============================================================================
-- COSTAREEN ERP - courier (Steadfast) append order
-- ----------------------------------------------------------------------------
-- Run AFTER 008. Idempotent.
--
-- The sheet's COURIER_PAYOUTS / _LINES / COURIER_RECON / COURIER_LOG tabs have
-- a row order several rules depend on: payouts are shown newest-first by the
-- order they were written; the first phone-matched line of an invoice is the
-- one auto-recorded; the "did not match" list is the newest 60. A batch of
-- rows written in one call shares one timestamp, so - as 008 did for the
-- other tabs - each of these tables gets a sequence number in write order.
-- ============================================================================

alter table public.courier_log          add column if not exists seq bigint generated by default as identity;
alter table public.courier_payouts      add column if not exists seq bigint generated by default as identity;
alter table public.courier_payout_lines add column if not exists seq bigint generated by default as identity;
alter table public.courier_recon        add column if not exists seq bigint generated by default as identity;

create index if not exists courier_payout_lines_seq_idx on public.courier_payout_lines(business_id, seq);
create index if not exists courier_recon_seq_idx on public.courier_recon(business_id, seq);

-- (no new tables: RLS for the four courier tables is already set in 007 section 12)

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on all functions in schema public to authenticated;
revoke all on public.business_secrets from anon, authenticated;
revoke all on public.erp_device_locks from anon, authenticated;
