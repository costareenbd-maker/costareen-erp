-- ============================================================================
-- COSTAREEN ERP - capital: who owns the business, whose money is in it
-- ----------------------------------------------------------------------------
-- Run AFTER 019. Idempotent. Mirrors the sheet tabs CAPITAL_HOLDERS,
-- CAPITAL_BOOK and CAPITAL_CLOSED (ERP.js build b261002-1321), plus the kept
-- copy of the dashboard that build introduced (erpDashReady_).
--
-- Reading is for shareholders and the owner; writing is the owner's alone.
-- A holder marked private is hidden from non-owners by the handler, which
-- still needs the row to keep the totals whole - so RLS lets shareholders
-- read every row, exactly as the sheet did.
-- ============================================================================

create table if not exists public.capital_holders (
  id           uuid primary key default gen_random_uuid(),
  business_id  uuid not null references public.businesses(id) on delete cascade,
  seq          bigint generated by default as identity,
  holder_no    text not null,              -- 'H' + 10 hex
  kind         text not null,              -- shareholder | investor
  name         text not null,
  phone        text,
  share_pct    numeric(7,2),
  return_kind  text,                       -- monthly | percent | none
  return_value numeric(14,2),
  since_month  text,                       -- yyyy-MM
  private      boolean not null default false,
  ended_month  text,
  note         text,
  set_by       text,
  set_at       timestamptz not null default now(),
  unique (business_id, holder_no)
);

create table if not exists public.capital_book (
  id           uuid primary key default gen_random_uuid(),
  business_id  uuid not null references public.businesses(id) on delete cascade,
  seq          bigint generated by default as identity,
  entry_no     text not null,              -- 'C' + yyMMddHHmmss + '-' + 3 digits
  recorded_at  timestamptz not null default now(),
  on_date      timestamptz,
  holder_no    text not null,
  type         text not null,              -- invest | withdraw | profit | ret
  amount       numeric(14,2) not null,
  method       text,
  note         text,
  by           text,
  voided       text,                       -- reason text; NULL = live
  expense_no   text,                       -- the expense a paid return created
  month        text
);
create index if not exists capital_book_idx on public.capital_book(business_id, seq);

create table if not exists public.capital_closed (
  business_id  uuid not null references public.businesses(id) on delete cascade,
  month        text not null,
  net_profit   numeric(14,2) not null,
  shares       jsonb not null,             -- { holder_no: pct } as they stood
  closed_at    timestamptz not null default now(),
  by           text,
  primary key (business_id, month)
);

do $$
declare t text;
begin
  foreach t in array array['capital_holders', 'capital_book', 'capital_closed']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %1$s_read on public.%1$s', t);
    execute format('create policy %1$s_read on public.%1$s for select using (public.is_shareholder(business_id))', t);
    execute format('drop policy if exists %1$s_insert on public.%1$s', t);
    execute format('create policy %1$s_insert on public.%1$s for insert with check (public.is_owner(business_id))', t);
    execute format('drop policy if exists %1$s_update on public.%1$s', t);
    execute format('create policy %1$s_update on public.%1$s for update using (public.is_owner(business_id)) with check (public.is_owner(business_id))', t);
  end loop;
end $$;

-- The dashboard, kept ready (erpDashReady_): one copy per business and sight
-- level ('full' for shareholder and owner, 'staff' below). RLS on with no
-- policy: only the Edge Function's privileged connection touches it.
create table if not exists public.erp_dash_cache (
  business_id uuid not null references public.businesses(id) on delete cascade,
  tier        text not null,
  day         text not null,               -- Dhaka yyyy-MM-dd it was worked out on
  dash        jsonb not null,
  kept_at     timestamptz not null default now(),
  primary key (business_id, tier)
);
alter table public.erp_dash_cache enable row level security;

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke all on public.erp_dash_cache from anon, authenticated;
revoke all on public.business_secrets from anon, authenticated;
revoke all on public.erp_device_locks from anon, authenticated;
