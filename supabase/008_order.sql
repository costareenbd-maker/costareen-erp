-- ============================================================================
-- COSTAREEN ERP - append order
-- ----------------------------------------------------------------------------
-- Run AFTER 007. Idempotent.
--
-- A sheet tab has an order: the order rows were written in. Several sheet ERP
-- rules depend on it (the first row of an invoice gives its customer; the
-- first PAYMENTS row wins ties; a backdated invoice sits where it was SAVED,
-- not where its date would put it). created_at cannot stand in for that,
-- because a backdated sale carries an old timestamp. So every table that
-- mirrors a tab gets a sequence number in write order.
-- ============================================================================

alter table public.invoices        add column if not exists seq bigint generated by default as identity;
alter table public.payments        add column if not exists seq bigint generated by default as identity;
alter table public.stock_movements add column if not exists seq bigint generated by default as identity;
alter table public.customers       add column if not exists seq bigint generated by default as identity;
alter table public.returns         add column if not exists seq bigint generated by default as identity;

create index if not exists invoices_seq_idx on public.invoices(business_id, seq);
create index if not exists payments_seq_idx on public.payments(business_id, seq);
create index if not exists invoices_no_idx on public.invoices(business_id, invoice_no);

grant usage, select on all sequences in schema public to authenticated;
