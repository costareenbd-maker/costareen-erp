-- ============================================================================
-- COSTAREEN ERP - product price and cost history
-- ----------------------------------------------------------------------------
-- Run AFTER 021. Idempotent.
--
-- The sheet kept only today's price and cost. Every change is now recorded by
-- the database itself (a trigger), so it cannot be forgotten by a screen:
-- who changed the selling price, wholesale price or cost, from what to what.
-- A stock receipt moves the cost by weighted average - that shows here too.
-- ============================================================================

create table if not exists public.product_changes (
  id          uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  product_id  uuid not null references public.products(id) on delete cascade,
  seq         bigint generated by default as identity,
  changed_at  timestamptz not null default now(),
  field       text not null,           -- sell_price | wholesale_price | cost_price | status
  was         text,
  now         text,
  changed_by  uuid
);
create index if not exists product_changes_idx on public.product_changes(product_id, seq);

create or replace function public.trg_product_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.sell_price is distinct from old.sell_price then
    insert into product_changes (business_id, product_id, field, was, now, changed_by)
    values (new.business_id, new.id, 'sell_price', old.sell_price::text, new.sell_price::text, auth.uid());
  end if;
  if new.wholesale_price is distinct from old.wholesale_price then
    insert into product_changes (business_id, product_id, field, was, now, changed_by)
    values (new.business_id, new.id, 'wholesale_price', old.wholesale_price::text, new.wholesale_price::text, auth.uid());
  end if;
  if new.cost_price is distinct from old.cost_price then
    insert into product_changes (business_id, product_id, field, was, now, changed_by)
    values (new.business_id, new.id, 'cost_price', old.cost_price::text, new.cost_price::text, auth.uid());
  end if;
  if new.status is distinct from old.status then
    insert into product_changes (business_id, product_id, field, was, now, changed_by)
    values (new.business_id, new.id, 'status', old.status, new.status, auth.uid());
  end if;
  return new;
end $$;

drop trigger if exists product_changes on public.products;
create trigger product_changes
  after update on public.products
  for each row execute function public.trg_product_changes();

alter table public.product_changes enable row level security;
drop policy if exists product_changes_read on public.product_changes;
create policy product_changes_read on public.product_changes
  for select using (public.is_member(business_id));
-- written only by the trigger (security definer); nobody inserts or edits by hand

revoke all on all functions in schema public from anon, public;
grant execute on all functions in schema public to authenticated;
grant select on public.product_changes to authenticated;
revoke all on public.product_changes from anon;
revoke all on public.business_secrets from anon, authenticated;
revoke all on public.erp_device_locks from anon, authenticated;
revoke all on public.erp_dash_cache   from anon, authenticated;
