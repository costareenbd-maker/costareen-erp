-- ============================================================================
-- COSTAREEN ERP - campaigns (WhatsApp)
-- ----------------------------------------------------------------------------
-- Run AFTER 007/008. Idempotent.
--
-- The campaign tabs are read in the order their rows were written (the
-- first matching CAMPAIGN_SENDS row is the one marked; the newest 50
-- campaigns are listed; a lead's last row wins). created_at / updated_at
-- cannot stand in for that (they change, or tie inside one batch), so each
-- table gets a write-order sequence number, as 008 did for the others.
-- ============================================================================

alter table public.campaigns         add column if not exists seq bigint generated by default as identity;
alter table public.campaign_sends    add column if not exists seq bigint generated by default as identity;
alter table public.campaign_optouts  add column if not exists seq bigint generated by default as identity;
alter table public.campaign_messages add column if not exists seq bigint generated by default as identity;
alter table public.campaign_groups   add column if not exists seq bigint generated by default as identity;
alter table public.campaign_leads    add column if not exists seq bigint generated by default as identity;

create index if not exists campaigns_no_idx         on public.campaigns(business_id, campaign_no);
create index if not exists campaigns_seq_idx        on public.campaigns(business_id, seq);
create index if not exists campaign_sends_seq_idx   on public.campaign_sends(business_id, seq);
create index if not exists campaign_sends_key_idx   on public.campaign_sends(business_id, customer_key);
create index if not exists campaign_optouts_key_idx on public.campaign_optouts(business_id, customer_key);
create index if not exists campaign_leads_key_idx   on public.campaign_leads(business_id, lead_key);
-- the spread timer looks for campaigns that send themselves
create index if not exists campaigns_spread_idx     on public.campaigns(business_id) where spread is not null;

-- RLS is already on for all six tables (007 section 12); nothing new here.

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on all functions in schema public to authenticated;
revoke all on public.business_secrets from anon, authenticated;
revoke all on public.erp_device_locks from anon, authenticated;
