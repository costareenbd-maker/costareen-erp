-- ============================================================================
-- COSTAREEN ERP - expenses + website orders
-- ----------------------------------------------------------------------------
-- Run AFTER 008. Idempotent.
--
-- EXPENSES / EXPENSE_ITEMS: the screen numbers the items (#1, #2 ...) in the
-- order they were set up, and "the last figure typed" wins - both are row
-- order on the sheet, so both tables get a write-order sequence (as 008 did
-- for the other tabs).
--
-- WEB_ORDERS: one sheet row per order LINE, with its own "entered" cell.
-- web_orders (one per order) + web_order_lines (one per line) hold the same
-- rows; the per-line flag and the line order are what the sheet had.
-- order_date_text keeps the website's own `created` text: the screen shows
-- its first 16 characters (ERP.js:1518), and the link guess reads its first
-- 10 as a Dhaka calendar day (ERP.js:10655).
-- ============================================================================

alter table public.expense_items   add column if not exists seq bigint generated by default as identity;
alter table public.expenses        add column if not exists seq bigint generated by default as identity;
create index if not exists expense_items_biz_idx on public.expense_items(business_id, seq);
create index if not exists expenses_no_idx       on public.expenses(business_id, expense_no);
create index if not exists expenses_item_idx     on public.expenses(business_id, item_no);

alter table public.web_orders      add column if not exists seq bigint generated by default as identity;
alter table public.web_orders      add column if not exists order_date_text text;
alter table public.web_order_lines add column if not exists seq bigint generated by default as identity;
alter table public.web_order_lines add column if not exists entered boolean not null default false;
alter table public.web_order_lines add column if not exists pulled_at timestamptz not null default now();
create index if not exists web_orders_seq_idx on public.web_orders(business_id, seq);
create index if not exists web_order_lines_biz_idx on public.web_order_lines(business_id, seq);

-- RLS: no new tables (expenses/expense_items are in 007's loop, web_orders /
-- web_order_lines in 001's).

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on all functions in schema public to authenticated;
revoke all on public.business_secrets from anon, authenticated;
revoke all on public.erp_device_locks from anon, authenticated;
