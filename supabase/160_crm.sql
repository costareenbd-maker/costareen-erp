-- 160 crm-1 (7 Nov 2026, owner: "G1 theke shuru kore ekdom shesh porjonto banaw").
--
-- The customer / lead upgrades from docs/CRM-GAP-VS-TWENTY.md, built into the ERP instead of moving the data to
-- Twenty. Additive only: new tables and new nullable columns. Idempotent.
--
--   crm_companies     G4  a shop, school or print farm; customers point at it (customers.company_id)
--   crm_fields        G5  the business's own fields on customers and leads (values in customers.extra / inbox_leads.extra)
--   crm_views         G3  saved list views (filters, conditions, sort, group), for one person or the whole team
--   crm_dupe_ok       G6  "these two are not the same person" (so the duplicate list stops showing the pair)
--   crm_events        G7  what happened (customer saved, invoice made, lead moved ...), for n8n and other tools
--   crm_hooks         G7  where those events are sent (the signing secret is sealed in business_secrets)
--   crm_rules         G8  when X happens, do Y (a follow-up, a lead stage, a note)
--   crm_bin           G9  a removed customer or lead, whole, until it is put back
--   crm_cal_feeds     G11/G12  the private calendar link (Google Calendar subscribes to it); only a hash is kept

alter table public.customers   add column if not exists company_id uuid;
alter table public.customers   add column if not exists extra jsonb not null default '{}'::jsonb;
alter table public.inbox_leads add column if not exists extra jsonb not null default '{}'::jsonb;

create table if not exists public.crm_companies (
  id          uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  name        text not null,
  kind        text,                       -- shop / school / print farm / company ...
  phone       text,
  address     text,
  note        text,
  by          text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create unique index if not exists crm_companies_name_idx on public.crm_companies (business_id, lower(btrim(name)));
create index if not exists customers_company_idx on public.customers (business_id, company_id) where company_id is not null;

create table if not exists public.crm_fields (
  id          uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  target      text not null check (target in ('customer', 'lead')),
  key         text not null,              -- f_<letters>, stable once made
  label       text not null,
  type        text not null default 'text' check (type in ('text', 'number', 'date', 'choice', 'yesno')),
  choices     text[] not null default '{}',
  hide_sales  boolean not null default false,
  sort        int not null default 0,
  removed_at  timestamptz,
  by          text,
  created_at  timestamptz not null default now()
);
create unique index if not exists crm_fields_key_idx on public.crm_fields (business_id, target, key);

create table if not exists public.crm_views (
  id          uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  target      text not null,              -- customers / leads
  name        text not null,
  state       jsonb not null default '{}'::jsonb,
  shared      boolean not null default false,
  owner_id    uuid,
  owner_name  text,
  created_at  timestamptz not null default now()
);
create index if not exists crm_views_idx on public.crm_views (business_id, target);

create table if not exists public.crm_dupe_ok (
  business_id uuid not null references public.businesses(id) on delete cascade,
  a           text not null,
  b           text not null,
  by          text,
  at          timestamptz not null default now(),
  primary key (business_id, a, b)
);

create table if not exists public.crm_events (
  id          bigint generated by default as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  kind        text not null,
  ref         text,
  data        jsonb not null default '{}'::jsonb,
  by          text,
  at          timestamptz not null default now(),
  sent        jsonb not null default '{}'::jsonb   -- {hookId: 'ok' | 'error text' | tries}
);
create index if not exists crm_events_idx on public.crm_events (business_id, id);

create table if not exists public.crm_hooks (
  id          uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  url         text not null,
  kinds       text[] not null default '{}',   -- empty = every kind
  on_         boolean not null default true,
  after_id    bigint not null default 0,      -- every event up to here has been sent (or given up)
  last_ok_at  timestamptz,
  last_error  text,
  by          text,
  created_at  timestamptz not null default now()
);

create table if not exists public.crm_rules (
  id          uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  name        text not null,
  when_kind   text not null,
  cond        jsonb not null default '{}'::jsonb,   -- {field, op, value}; empty = always
  act         text not null check (act in ('followup', 'lead_stage', 'lead_followup', 'note')),
  params      jsonb not null default '{}'::jsonb,
  on_         boolean not null default true,
  runs        int not null default 0,
  last_run_at timestamptz,
  by          text,
  created_at  timestamptz not null default now()
);

create table if not exists public.crm_bin (
  id          uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  kind        text not null check (kind in ('customer', 'lead')),
  label       text not null,
  row_data    jsonb not null,
  extra_data  jsonb not null default '{}'::jsonb,
  reason      text,
  removed_by  text,
  removed_at  timestamptz not null default now(),
  restored_by text,
  restored_at timestamptz
);
create index if not exists crm_bin_idx on public.crm_bin (business_id, removed_at desc);

create table if not exists public.crm_cal_feeds (
  business_id uuid primary key references public.businesses(id) on delete cascade,
  token_hash  text not null,
  by          text,
  created_at  timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['crm_companies', 'crm_fields', 'crm_views', 'crm_dupe_ok', 'crm_events', 'crm_hooks', 'crm_rules', 'crm_bin', 'crm_cal_feeds'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_rw', t);
    execute format('create policy %I on public.%I for all to authenticated using (business_id in (select public.my_business_ids(''member''))) with check (business_id in (select public.my_business_ids(''member'')))', t || '_rw', t);
    execute format('grant select, insert, update on public.%I to authenticated', t);
  end loop;
end $$;
-- the duplicate "not the same" marks and the bin's restore take rows out again
grant delete on public.crm_dupe_ok, public.crm_views to authenticated;
grant usage, select on all sequences in schema public to authenticated;
