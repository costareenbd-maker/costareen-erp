// ui-6: my name and photo, the business's background photo, switching it off for myself, "auto" appearance.
import { owner, mgr, sales, check, done } from './harness.mjs';
const PIC = 'data:image/jpeg;base64,' + 'A'.repeat(400);
let r = await owner('erpProfile', []);
check('who I am', r.ok && r.result.role === 'owner' && 'avatar' in r.result, r.result);
r = await sales('erpProfileSave', [{ avatar: PIC, name: 'Rina S' }]);
check('anyone sets their own name and photo', r.ok && r.result.avatar === PIC && r.result.name === 'Rina S', r);
r = await sales('erpProfileSave', [{ avatar: 'javascript:alert(1)' }]);
check('only a real picture', !r.ok, r);
r = await sales('erpProfileSave', [{ avatar: '' }]);
check('photo removed', r.ok && !r.result.avatar, r.result);
r = await sales('erpBgSave', [{ photo: PIC }]);
check('sales staff cannot set the background photo', !r.ok, r);
r = await mgr('erpBgSave', [{ photo: PIC, strength: 'strong' }]);
check('a manager sets it', r.ok && r.result.photo === PIC && r.result.strength === 'strong', r);
r = await sales('erpBg', []);
check('everyone sees it', r.ok && r.result.photo === PIC && !r.result.off, r);
r = await sales('erpBgOff', [{ off: true }]);
check('switched off for one person', r.ok && r.result.off, r);
r = await owner('erpBg', []);
check('...not for the others', r.ok && !r.result.off);
r = await owner('erpSetTheme', ['auto']);
check('"auto" appearance is kept', r.ok && r.result.theme === 'auto', r);
await done();
