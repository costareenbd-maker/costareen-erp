// Plan D3 (first half): product photos.
import { sql, FIX, owner, mgr, sales, check, done, files } from './harness.mjs';
const PLA = 'FIL-SUN-PLA-BLA-001';
const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';
const thumb = 'data:image/jpeg;base64,' + png;

let r = await sales('erpProductThumbs', []);
check('no photos to begin with', r.ok && Object.keys(r.result.thumbs).length === 0, r);
r = await sales('erpProductPhoto', [{ sku: PLA, file: { data: png, mime: 'image/png' }, thumb }]);
check('sales staff cannot change a photo', !r.ok, r);
r = await mgr('erpProductPhoto', [{ sku: 'NOPE', file: { data: png, mime: 'image/png' }, thumb }]);
check('unknown product', !r.ok && /no longer on the list/.test(r.error), r);
r = await mgr('erpProductPhoto', [{ sku: PLA, file: { data: png, mime: 'application/pdf' }, thumb }]);
check('only pictures', !r.ok && /JPG, PNG or WebP/.test(r.error), r);
r = await mgr('erpProductPhoto', [{ sku: PLA, file: { data: png, mime: 'image/png' }, thumb: 'javascript:alert(1)' }]);
check('the small picture must be a plain image data URL', !r.ok && /small picture/.test(r.error), r);
r = await mgr('erpProductPhoto', [{ sku: PLA, file: { data: png, mime: 'image/png' }, thumb: 'data:image/svg+xml;base64,' + png }]);
check('...and never an SVG', !r.ok && /small picture/.test(r.error), r);
r = await mgr('erpProductPhoto', [{ sku: PLA.toLowerCase(), file: { data: png, mime: 'image/png' }, thumb }]);
check('photo kept', r.ok && r.result.photo === true && r.result.sku === PLA && files.list().some((k) => k.startsWith(FIX.B + '/products/FIL-SUN-PLA-BLA-001-')), files.list());
r = await sales('erpProductThumbs', []);
check('the small picture travels with the list, by product code', r.ok && r.result.thumbs[PLA.toLowerCase()] === thumb, r.result);
r = await sales('erpProductPhotoUrl', [{ sku: PLA }]);
check('a link to the full picture', r.ok && /^https:\/\/files\.test\/.+products/.test(r.result.url), r);
r = await mgr('erpProductPhoto', [{ sku: PLA, file: { data: png, mime: 'image/jpeg' }, thumb }]);
check('a new photo replaces the old one', r.ok && files.list().filter((k) => k.includes('/products/')).length === 1 && files.list().some((k) => /\.jpg$/.test(k)), files.list());
r = await mgr('erpProductPhoto', [{ sku: PLA, remove: true }]);
check('removed: file gone, list clean', r.ok && !files.list().some((k) => k.includes('/products/')) && Object.keys((await sales('erpProductThumbs', [])).result.thumbs).length === 0, files.list());
r = await sales('erpProductPhotoUrl', [{ sku: PLA }]);
check('no link when there is no photo', !r.ok && /No photo/.test(r.error), r);
const other = await sql`select count(*)::int n from products where business_id = ${FIX.B2} and thumb is not null`;
check('another business untouched', other[0].n === 0);

// ---------------------------------------------------------------- colour families
r = await sales('erpFamilies', []);
check('families are a manager matter', !r.ok, r);
r = await mgr('erpFamilies', []);
check('nothing grouped yet; groups are suggested by category + brand + type', r.ok && r.result.families.length === 0 && Array.isArray(r.result.proposals), r.result && [r.result.total, r.result.proposals.length]);
const all = await sql`select sku, type, brand, category from products where business_id = ${FIX.B} order by sku`;
const two = all.slice(0, 2).map((x) => x.sku);
const stockBefore = await sql`select p.sku, ps.stock from products p join product_stock ps on ps.product_id = p.id where p.business_id = ${FIX.B} order by p.sku`;
r = await mgr('erpFamilyApply', [{ groups: [] }]);
check('nothing ticked', !r.ok && /Tick at least one/.test(r.error), r);
r = await mgr('erpFamilyApply', [{ groups: [{ name: '', skus: two }] }]);
check('a family needs a name', !r.ok && /needs a name/.test(r.error), r);
r = await mgr('erpFamilyApply', [{ groups: [{ name: 'Test Family', skus: [two[0].toLowerCase(), two[1], 'NOT-A-SKU'] }] }]);
check('two products grouped; an unknown code is ignored', r.ok && r.result.changed === 2 && r.result.families.length === 1 && r.result.families[0].products.length === 2, r.result && r.result.families);
r = await sales('erpCatalog', []);
check('the catalogue carries the family', r.ok && r.result.filter((p) => p.family === 'Test Family').length === 2, r.result && r.result.slice(0, 2));
const stockAfter = await sql`select p.sku, ps.stock from products p join product_stock ps on ps.product_id = p.id where p.business_id = ${FIX.B} order by p.sku`;
check('codes and stock are untouched', JSON.stringify(stockBefore) === JSON.stringify(stockAfter));
r = await sales('erpListView', [{ model: 'products', groupBy: 'family' }]);
check('the product list can be grouped by family', r.ok && JSON.stringify(r.result).includes('Test Family'), r.ok ? Object.keys(r.result) : r);
r = await mgr('erpFamilyClear', [{ sku: two[0] }]);
check('one product taken out', r.ok && r.result.changed === 1 && r.result.families[0].products.length === 1, r.result && r.result.families);
r = await mgr('erpFamilyClear', [{ name: 'Test Family' }]);
check('the family taken apart: all as before', r.ok && r.result.families.length === 0 && (await sql`select count(*)::int n from products where business_id = ${FIX.B} and family is not null`)[0].n === 0, r.result && r.result.families);
const o2 = await sql`select count(*)::int n from products where business_id = ${FIX.B2} and family is not null`;
check('another business has no families', o2[0].n === 0);
await done();
