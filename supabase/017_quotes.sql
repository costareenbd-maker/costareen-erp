-- ============================================================================
-- COSTAREEN ERP - quotations (group 'quotes')
-- ----------------------------------------------------------------------------
-- Run AFTER 008. Idempotent.
--
-- QUOTE_ITEMS had an order (rows in the order they were first added; an
-- update rewrote a row in place). added_at cannot stand in for it, because an
-- update rewrites added_at too. Same device as 008: a write-order number.
-- The quotation list itself is ordered by updated_at, so QUOTATIONS needs none.
-- ============================================================================

alter table public.quote_items add column if not exists seq bigint generated by default as identity;
create index if not exists quote_items_seq_idx on public.quote_items(business_id, seq);
create index if not exists quotations_updated_idx on public.quotations(business_id, updated_at desc);

-- (no new table: RLS for quotations / quote_settings / quote_items is in 007)

grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on all functions in schema public to authenticated;
revoke all on public.business_secrets from anon, authenticated;
revoke all on public.erp_device_locks from anon, authenticated;
