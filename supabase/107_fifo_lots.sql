-- 107: FIFO stock lots (FilaDash merge P3, owner decision F1 - docs/FILADASH-MERGE-REVIEW.md).
--
-- Every unit in stock belongs to a lot: what came in together, at one landed cost per unit. A sale (or any
-- stock going out) takes from the oldest lot first; the cost of what it took is what the sale cost (the page
-- writes it on the invoice line). It is kept by the database itself, from stock_movements, so every way stock
-- moves - invoices, receiving, counts, damage, repairs, joint stock, returns - is covered without each one
-- having to remember.
--
--   stock_lots  one row per lot: qty_in, qty_left, unit_cost (null = not known: stock from before lots began;
--               the product's cost book price stands in for it), where it came from.
--   lot_draws   what each movement took from which lot (qty > 0), or put back into it (qty < 0, a return).
--
-- A product's lots begin the first time its stock moves after this: what was on the shelf then becomes one
-- 'opening' lot (cost not known), so older stock is still sold first. MOVE (stock changing hands inside a
-- joint pool) does not touch lots. Deleting a movement (an invoice removed) undoes what it did to the lots.

create table if not exists public.stock_lots (
  id           uuid primary key default gen_random_uuid(),
  business_id  uuid not null references public.businesses(id) on delete cascade,
  product_id   uuid not null references public.products(id) on delete cascade,
  movement_id  uuid references public.stock_movements(id) on delete set null,
  source       text not null check (source in ('opening', 'receive', 'return', 'adjust')),
  reference    text,
  supplier     text,
  received_at  timestamptz not null,
  qty_in       numeric(14,2) not null,
  qty_left     numeric(14,2) not null,
  unit_cost    numeric(14,2),
  seq          bigint generated by default as identity,
  created_at   timestamptz not null default now()
);
create index if not exists stock_lots_open_idx on public.stock_lots (product_id, received_at, seq) where qty_left > 0;
create index if not exists stock_lots_biz_idx on public.stock_lots (business_id, received_at desc);
create index if not exists stock_lots_ref_idx on public.stock_lots (business_id, reference);

create table if not exists public.lot_draws (
  id           uuid primary key default gen_random_uuid(),
  business_id  uuid not null references public.businesses(id) on delete cascade,
  movement_id  uuid not null references public.stock_movements(id) on delete cascade,
  lot_id       uuid references public.stock_lots(id) on delete set null,
  product_id   uuid not null,
  qty          numeric(14,2) not null,
  unit_cost    numeric(14,2),
  of_draw      uuid references public.lot_draws(id) on delete set null,   -- a return: the sale draw it puts back
  reversed     numeric(14,2) not null default 0,                           -- a sale draw: how much came back since
  at           timestamptz not null default now()
);
create index if not exists lot_draws_move_idx on public.lot_draws (movement_id);
create index if not exists lot_draws_lot_idx on public.lot_draws (lot_id);
create index if not exists lot_draws_prod_idx on public.lot_draws (product_id, at);

alter table public.stock_lots enable row level security;
alter table public.lot_draws enable row level security;
drop policy if exists stock_lots_read on public.stock_lots;
create policy stock_lots_read on public.stock_lots for select to authenticated
  using (business_id in (select public.my_business_ids('member')));
drop policy if exists lot_draws_read on public.lot_draws;
create policy lot_draws_read on public.lot_draws for select to authenticated
  using (business_id in (select public.my_business_ids('member')));
grant select on public.stock_lots, public.lot_draws to authenticated;
-- the page sets a lot's cost after a return of a sale from before lots (the cost written on the sold line)
drop policy if exists stock_lots_cost on public.stock_lots;
create policy stock_lots_cost on public.stock_lots for update to authenticated
  using (business_id in (select public.my_business_ids('manager')))
  with check (business_id in (select public.my_business_ids('manager')));
grant update (unit_cost) on public.stock_lots to authenticated;

-- what was on the shelf before this movement, made into the product's first ('opening') lot
create or replace function public.lots_begin(p_biz uuid, p_product uuid, p_skip uuid, p_at timestamptz)
returns void language plpgsql security definer set search_path = public as $$
declare v_had numeric;
begin
  if exists (select 1 from stock_lots where product_id = p_product) then return; end if;
  select coalesce(sum(case when direction = 'IN' then qty else -qty end), 0) into v_had
    from stock_movements where product_id = p_product and id <> p_skip;
  if v_had > 0 then
    insert into stock_lots (business_id, product_id, source, reference, received_at, qty_in, qty_left, unit_cost)
    values (p_biz, p_product, 'opening', 'Stock before lots began', p_at - interval '1 millisecond', v_had, v_had, null);
  else
    -- nothing on the shelf: an empty marker so the next movement does not count the past again
    insert into stock_lots (business_id, product_id, source, reference, received_at, qty_in, qty_left, unit_cost)
    values (p_biz, p_product, 'opening', 'Stock before lots began', p_at - interval '1 millisecond', 0, 0, null);
  end if;
end $$;

create or replace function public.lots_follow() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_left numeric; v_take numeric; v_lot record; v_draw record; v_orig uuid; v_cost numeric; v_src text;
begin
  if new.kind::text = 'MOVE' then return new; end if;
  perform lots_begin(new.business_id, new.product_id, new.id, new.created_at);

  if new.direction = 'OUT' then
    v_left := new.qty;
    for v_lot in select * from stock_lots where product_id = new.product_id and qty_left > 0
                 order by received_at, seq for update loop
      exit when v_left <= 0;
      v_take := least(v_left, v_lot.qty_left);
      update stock_lots set qty_left = qty_left - v_take where id = v_lot.id;
      insert into lot_draws (business_id, movement_id, lot_id, product_id, qty, unit_cost, at)
      values (new.business_id, new.id, v_lot.id, new.product_id, v_take, v_lot.unit_cost, new.created_at);
      v_left := v_left - v_take;
    end loop;
    if v_left > 0 then
      -- more went out than the lots hold (stock below zero): taken at no lot, its cost not known
      insert into lot_draws (business_id, movement_id, lot_id, product_id, qty, unit_cost, at)
      values (new.business_id, new.id, null, new.product_id, v_left, null, new.created_at);
    end if;
    return new;
  end if;

  -- IN
  v_left := new.qty;
  if new.kind::text = 'RETURN' then
    -- goods back from a customer: into the very lots the sale took them from, newest draw first
    if new.reference like 'Return: %' then
      select id into v_orig from invoices
        where business_id = new.business_id and invoice_no = btrim(substr(new.reference, 9)) limit 1;
    end if;
    if v_orig is not null then
      for v_draw in select d.* from lot_draws d join stock_movements m on m.id = d.movement_id join stock_lots sl on sl.id = d.lot_id
                    where m.invoice_id = v_orig and m.direction = 'OUT' and d.product_id = new.product_id
                      and d.qty > 0 and d.qty - d.reversed > 0
                    order by d.at desc, sl.received_at desc, sl.seq desc for update of d loop
        exit when v_left <= 0;
        v_take := least(v_left, v_draw.qty - v_draw.reversed);
        update lot_draws set reversed = reversed + v_take where id = v_draw.id;
        update stock_lots set qty_left = qty_left + v_take where id = v_draw.lot_id;
        insert into lot_draws (business_id, movement_id, lot_id, product_id, qty, unit_cost, of_draw, at)
        values (new.business_id, new.id, v_draw.lot_id, new.product_id, -v_take, v_draw.unit_cost, v_draw.id, new.created_at);
        v_left := v_left - v_take;
      end loop;
      if v_left > 0 then
        -- sold before lots began: a new lot at the cost written on the sold line
        select nullif(l.unit_cost, 0) into v_cost from invoice_lines l
          where l.invoice_id = v_orig and l.product_id = new.product_id and l.qty > 0 order by l.line_no limit 1;
      end if;
    end if;
    v_src := 'return';
  elsif new.kind::text = 'RECEIVE' then
    v_src := 'receive'; v_cost := nullif(new.unit_price, 0);
  elsif new.kind::text = 'OPENING' then
    v_src := 'opening'; v_cost := nullif(new.unit_price, 0);
  else
    v_src := 'adjust';
  end if;
  if v_left > 0 then
    insert into stock_lots (business_id, product_id, movement_id, source, reference, supplier, received_at, qty_in, qty_left, unit_cost)
    values (new.business_id, new.product_id, new.id, v_src, new.reference, nullif(new.supplier, ''), new.created_at, v_left, v_left, v_cost);
  end if;
  return new;
end $$;

-- a movement removed (an invoice deleted, a count undone): what it did to the lots is undone
create or replace function public.lots_unfollow() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_draw record;
begin
  if old.kind::text = 'MOVE' then return old; end if;
  for v_draw in select * from lot_draws where movement_id = old.id loop
    if v_draw.lot_id is not null then
      update stock_lots set qty_left = qty_left + v_draw.qty where id = v_draw.lot_id;
    end if;
    if v_draw.of_draw is not null then
      update lot_draws set reversed = greatest(0, reversed + v_draw.qty) where id = v_draw.of_draw;
    end if;
  end loop;
  delete from lot_draws where movement_id = old.id;
  -- the lot this movement brought in: gone with it (what was already taken from it stays taken, at no lot)
  update lot_draws set lot_id = null where lot_id in (select id from stock_lots where movement_id = old.id);
  delete from stock_lots where movement_id = old.id;
  return old;
end $$;

drop trigger if exists stock_movements_lots on public.stock_movements;
create trigger stock_movements_lots after insert on public.stock_movements
  for each row execute function public.lots_follow();
drop trigger if exists stock_movements_unlots on public.stock_movements;
create trigger stock_movements_unlots before delete on public.stock_movements
  for each row execute function public.lots_unfollow();
