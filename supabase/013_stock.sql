-- ============================================================================
-- COSTAREEN ERP - stock group (products, receiving, purchase orders)
-- ----------------------------------------------------------------------------
-- Run AFTER 008. Idempotent.
--
-- PURCHASE_ORDERS, PO_SHIPMENTS and PO_DIFFS are read in the order their rows
-- were written (erpPoOpen_ takes the order's rate from its first row; a
-- difference is found by the first row with its id). Several rows are written
-- in one transaction, so created_at cannot give that order - a write-order
-- sequence does, exactly as 008 did for the other tabs.
-- ============================================================================

alter table public.po_lines     add column if not exists seq bigint generated by default as identity;
alter table public.po_shipments add column if not exists seq bigint generated by default as identity;
alter table public.po_diffs     add column if not exists seq bigint generated by default as identity;

create index if not exists po_lines_seq_idx     on public.po_lines(business_id, seq);
create index if not exists po_shipments_seq_idx on public.po_shipments(business_id, po_no, seq);
create index if not exists po_diffs_seq_idx     on public.po_diffs(business_id, seq);
create index if not exists po_diffs_no_idx      on public.po_diffs(business_id, diff_no);
create index if not exists movements_seq_idx    on public.stock_movements(business_id, seq);

-- grants (same lines as 007 section 13)
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on all functions in schema public to authenticated;
revoke all on public.business_secrets from anon, authenticated;
revoke all on public.erp_device_locks from anon, authenticated;
